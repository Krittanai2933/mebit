#[derive(Clone, Copy, Debug, PartialEq, Eq, uniffi::Enum)]
pub enum WalletKind {
    Jade,
    TrezorSafe7,
}

/// A wallet a scan saw. Pass it to `WalletLink` unchanged.
#[derive(Clone, Debug, PartialEq, Eq, uniffi::Record)]
pub struct FoundWallet {
    pub kind: WalletKind,
    /// The platform's handle for the device, stable while the app runs. Use it as a list key.
    pub id: String,
    /// The advertised name, e.g. `Jade 1a2b3c`.
    pub name: String,
}

/// An account extended public key read from a hardware wallet.
#[derive(Clone, Debug, PartialEq, Eq, uniffi::Record)]
pub struct HwAccountKey {
    /// `xpub` on mainnet, `tpub` on test networks. Not a SLIP-132 form.
    pub xpub: String,
    /// Master key fingerprint, 8 lowercase hex characters.
    pub master_fingerprint: String,
    /// The path the key was derived on, such as `m/48'/1'/0'/2'`.
    pub derivation_path: String,
}

/// Who answered on a connected link.
#[derive(Clone, Debug, PartialEq, Eq, uniffi::Record)]
pub struct WalletInfo {
    pub name: String,
    /// The firmware version, e.g. `1.0.41`.
    pub firmware: String,
    pub details: WalletDetails,
}

/// What only one vendor reports. The variant is the vendor.
#[derive(Clone, Debug, PartialEq, Eq, uniffi::Enum)]
pub enum WalletDetails {
    Jade {
        /// `JADE_V2C` is a Jade Core.
        board: String,
        state: JadeState,
        /// `MAIN` or `TEST` once the wallet is pinned to a network type, `ALL` before.
        networks: String,
    },
    /// Read once, during connect.
    TrezorSafe7 {
        /// Always `T3W1`.
        internal_model: String,
        /// Random per device, regenerated by a wipe.
        device_id: Option<String>,
        label: Option<String>,
        /// The link's ATT MTU, at least 247.
        mtu: u16,
    },
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, uniffi::Enum)]
pub enum JadeState {
    /// No wallet on the device.
    Uninit,
    /// A recovery phrase entered but not saved behind a PIN yet.
    Unsaved,
    /// A saved wallet, not unlocked over this link.
    Locked,
    /// Unlocked over this link.
    Ready,
    /// A Temporary Signer wallet, forgotten on reboot.
    Temp,
}

/// Every failure a Bluetooth export returns.
///
/// Flat, like `MobileSignerError`: Kotlin branches on the subclass, and `message` is the
/// vendor crate's own text, which says what to do. Kotlin reads variants by position, so
/// append new ones and run `scripts/ffi.sh build`.
#[derive(Clone, Debug, PartialEq, Eq, thiserror::Error, uniffi::Error)]
#[uniffi(flat_error)]
pub enum BleError {
    /// This build or this process cannot use Bluetooth. On Android, `System.loadLibrary`
    /// did not run before the first Bluetooth call.
    #[error("{0}")]
    Unsupported(String),
    /// The OS refused Bluetooth to this app. Android: ask for the permissions again.
    /// iOS: Settings.
    #[error("{0}")]
    PermissionDenied(String),
    /// There is no usable adapter: on Android, Bluetooth is fully off or missing, and the scanner
    /// is null. An Android adapter that stays in `BLE_ON` after the switch is turned off scans
    /// nothing and gives `NotFound` instead. iOS never reports this (read from btleplug's source,
    /// not run): with Bluetooth off, a scan finds nothing and fails as `NotFound`.
    #[error("{0}")]
    BluetoothOff(String),
    /// No wallet of that kind was seen. The message says whether anything was seen at all.
    /// With Bluetooth off, iOS ends up here too (read from btleplug's source, not run), and so
    /// does an Android adapter in `BLE_ON`. On Android 11 and below, so does a missing location
    /// permission or Location switched off.
    #[error("{0}")]
    NotFound(String),
    /// Not a wallet this app supports: another Trezor model, older firmware, no wallet service.
    #[error("{0}")]
    WrongDevice(String),
    /// Nobody typed the pairing code, or the wallet's own cancel button ended pairing.
    #[error("{0}")]
    PairingCancelled(String),
    /// Pairing did not finish. The Safe 7 refused the code, or the OS pairing was declined or not
    /// confirmed in time, which iOS reports as this error for a Safe 7. Elsewhere that case
    /// arrives as `Disconnected` while connecting, or as `Timeout` after a Jade's stalled service
    /// discovery, with a hint in the text. A Jade on Android holds its pairing request in the
    /// first request after connect, and a declined one ends that request as `Disconnected` or
    /// `Timeout` with the same hint. A Jade that lost power gives the same errors.
    #[error("{0}")]
    PairingFailed(String),
    /// The wallet forgot this phone's Bluetooth bond (a Safe 7 that was restored or removed the
    /// phone, a Jade that paired other hosts): forget it in Settings and connect again. Android
    /// can re-pair by itself instead of raising this.
    #[error("{0}")]
    BondRemoved(String),
    /// The request was refused, by the wallet (declined, locked, busy, not set up) or before
    /// it was sent. The link stays usable.
    #[error("{0}")]
    Refused(String),
    /// A step took too long. For a Jade, a service discovery that stalls, or on Android a first
    /// request that stalls, can be a pairing request that nobody answered, and the text says so.
    #[error("{0}")]
    Timeout(String),
    /// The link is down or closed. Connect again. While connecting, or in a Jade's first request
    /// on Android, it can mean a pairing request that nobody confirmed in time, and the text says
    /// so. A Jade that lost power drops the link the same way, so the text is a hint, not a
    /// diagnosis.
    #[error("{0}")]
    Disconnected(String),
    /// Any other Bluetooth failure: connecting, MTU, GATT.
    #[error("{0}")]
    Link(String),
    /// A bug, or a wallet out of step with this app. Connect again, and report it.
    #[error("{0}")]
    Protocol(String),
    /// The device holds no key of the wallet it was asked to sign for: no key with its master
    /// fingerprint, or another key at that key's path. Nothing showed on the device, and the link
    /// stays usable.
    #[error("{0}")]
    WrongKey(String),
}

impl BleError {
    fn leaves_link_usable(&self) -> bool {
        matches!(self, Self::Refused(_) | Self::WrongKey(_))
    }
}

fn closed() -> BleError {
    BleError::Disconnected("the link is closed; connect again".into())
}

/// Asks the user for the six digits a Trezor Safe 7 shows while pairing (not its PIN).
/// Return null if the user gives up, and never throw: an exception cannot be mapped, so the
/// connect fails with `InternalException`. It may be asked again on one connect when an answer
/// is not six digits. A Jade never asks.
#[uniffi::export(with_foreign)]
#[async_trait::async_trait]
pub trait PairingCodes: Send + Sync {
    async fn pairing_code(&self) -> Option<String>;
}

/// Scans for a few seconds and lists the wallets of `kind` in range.
/// Cancelling stops the scan.
#[uniffi::export(async_runtime = "tokio")]
pub async fn scan_wallets(kind: WalletKind) -> Result<Vec<FoundWallet>, BleError> {
    platform::ble_ready()?;
    platform::forget_seen_devices().await?;
    backend::scan(kind).await
}

/// A link to one wallet that `scan_wallets` found. Make it, call `connect`, close it when done.
///
/// A task owns the device and this object sends it requests, so a cancelled call never leaves
/// the device half-way through an exchange. Closing this object starts the disconnect, once no
/// call is still running on it, and returns before the link is down: cancel the call first, and
/// use `disconnect()` to wait. A link connects once: after a failed or cancelled `connect`,
/// make a new one.
///
/// A call made on a coroutine that is already cancelled throws before it starts and leaves
/// nothing behind, so `close()` still releases the link. Wrap a call that must run after a
/// cancel, such as `disconnect()` to wait for the link to be down, in `withContext(NonCancellable)`.
#[derive(uniffi::Object)]
pub struct WalletLink {
    wallet: FoundWallet,
    claimed: AtomicBool,
    running: OnceLock<Running>,
}

/// The connected half of a link: the way to the task that owns the device.
struct Running {
    requests: mpsc::UnboundedSender<Request>,
    _link_dropped: oneshot::Sender<()>,
    /// Closes when the task ends, which is after the link is down.
    task_ended: mpsc::Sender<()>,
}

static LIVE_WALLET_LINKS: AtomicU64 = AtomicU64::new(0);

impl Drop for WalletLink {
    fn drop(&mut self) {
        LIVE_WALLET_LINKS.fetch_sub(1, Ordering::SeqCst);
    }
}

/// How many `WalletLink` objects exist in this process. For tests, not a stable API: a link
/// that a call kept alive after `close()` still counts here.
#[uniffi::export]
pub fn live_wallet_links() -> u64 {
    LIVE_WALLET_LINKS.load(Ordering::SeqCst)
}

enum Request {
    Info(oneshot::Sender<Result<WalletInfo, BleError>>),
    Unlock(oneshot::Sender<Result<(), BleError>>),
    Xpub {
        path: String,
        reply: oneshot::Sender<Result<HwAccountKey, BleError>>,
    },
    SignPsbt {
        psbt_base64: String,
        signer_fingerprint: String,
        reply: oneshot::Sender<Result<String, BleError>>,
    },
    SignWallet {
        wallet: Box<Described>,
        shown: SpendReview,
        reply: oneshot::Sender<Result<SpendReview, BleError>>,
    },
    Disconnect(oneshot::Sender<Result<(), BleError>>),
}

fn parse_derivation_path(path: &str) -> Result<DerivationPath, BleError> {
    DerivationPath::from_str(path)
        .map_err(|error| BleError::Refused(format!("invalid derivation path: {error}")))
}

/// Why a payment check refused, without the "invalid PSBT json" its error variant adds: none of them reads JSON.
fn said(error: MobileSignerError) -> String {
    match error {
        MobileSignerError::InvalidPsbtJson(why) => why,
        other => other.to_string(),
    }
}

fn derivation_path_string(path: &DerivationPath) -> String {
    if path.is_master() {
        "m".to_owned()
    } else {
        format!("m/{path}")
    }
}

#[uniffi::export(async_runtime = "tokio")]
impl WalletLink {
    /// Makes a link that is not connected yet. It exists before `connect` starts, so a
    /// `connect` cancelled at any moment leaves nothing that cannot be closed.
    #[uniffi::constructor]
    pub fn new(wallet: FoundWallet) -> Arc<Self> {
        LIVE_WALLET_LINKS.fetch_add(1, Ordering::SeqCst);
        Arc::new(Self {
            wallet,
            claimed: AtomicBool::new(false),
            running: OnceLock::new(),
        })
    }

    /// Connects to the wallet, pairs if it must, and checks the wallet is what it says.
    /// Cancelling while it runs leaves nothing that closing the link cannot end: measured with a
    /// Jade, unit-tested with a fake central for a Safe 7. A Jade that fails disconnects in the
    /// background, a Safe 7 before this returns.
    ///
    /// `pairing` is a Safe 7 credential an earlier connect returned, so the Safe 7 asks only to
    /// allow the connection. Unreadable bytes are dropped and the Safe 7 then pairs with a code.
    /// Returns the credential to keep when this connect paired with a code (the first pairing, or a
    /// kept one the Safe 7 no longer knows), else null. It is a secret: keep it in the Keychain or
    /// Keystore. A Jade ignores `pairing` and returns null.
    pub async fn connect(
        &self,
        codes: Arc<dyn PairingCodes>,
        pairing: Option<Vec<u8>>,
    ) -> Result<Option<Vec<u8>>, BleError> {
        platform::ble_ready()?;
        self.attach(async {
            platform::forget_seen_devices().await?;
            backend::connect(&self.wallet, codes, pairing).await
        })
        .await
    }

    /// Name, firmware and what only this vendor reports. Cancelling stops only the wait:
    /// the wallet finishes the exchange and the link stays usable.
    pub async fn info(&self) -> Result<WalletInfo, BleError> {
        self.running.get().ok_or_else(closed)?.info().await
    }

    /// Unlocks the wallet for this connection.
    ///
    /// A Jade asks for its PIN on the device, unless it is a Temporary Signer.
    /// A Safe 7 has no separate unlock. Connect already opened the session, so
    /// this returns immediately. Cancelling stops only the wait. A refusal
    /// leaves the link up.
    pub async fn unlock(&self) -> Result<(), BleError> {
        self.running.get().ok_or_else(closed)?.unlock().await
    }

    /// The account extended public key at `derivation_path`.
    ///
    /// `derivation_path` is a BIP-32 path such as `m/48'/1'/0'/2'`. An unreadable
    /// path is refused and the link stays up. A Jade must be unlocked first.
    /// The master fingerprint is 8 lowercase hex characters. Cancelling stops
    /// only the wait. A refusal leaves the link up.
    pub async fn account_xpub(&self, derivation_path: String) -> Result<HwAccountKey, BleError> {
        self.running
            .get()
            .ok_or_else(closed)?
            .account_xpub(derivation_path)
            .await
    }

    /// Has the hardware wallet sign `psbt_base64` for `signer_fingerprint`.
    ///
    /// `psbt_base64` is a BIP-174 PSBT. `signer_fingerprint` is 8 lowercase hex
    /// characters (the vault key's master fingerprint). Jade must be unlocked
    /// first. Returns the signed PSBT as base64. Callers must run spend policy
    /// before this (vault-core policy against real PSBTs is still Term-2 work;
    /// the app checks destination and amount at the UI boundary today).
    pub async fn sign_psbt(
        &self,
        psbt_base64: String,
        signer_fingerprint: String,
    ) -> Result<String, BleError> {
        self.running
            .get()
            .ok_or_else(closed)?
            .sign_psbt(psbt_base64, signer_fingerprint)
            .await
    }

    /// Signs `psbt_base64`, a payment of the wallet `descriptor` whose unsigned id is
    /// `unsigned_txid` (the payment the user was shown), with the key of that wallet this device
    /// holds, and returns what the PSBT says after it. Before anything reaches the device, it
    /// refuses a descriptor `wallet_describe` refuses, a PSBT `wallet_review` refuses, and a PSBT
    /// whose id is another ("changed since shown"). `WrongKey` means the device holds no key of the
    /// wallet, and nothing showed on it. When that key has already signed, the review comes back
    /// without asking the device to sign. Else the device shows the payment, and its answer is
    /// refused unless that key then signed every input. A Jade must be unlocked first. Cancelling
    /// stops only the wait: the device finishes the request.
    pub async fn sign_wallet_psbt(
        &self,
        descriptor: String,
        psbt_base64: String,
        unsigned_txid: String,
    ) -> Result<SpendReview, BleError> {
        let refused = |error| BleError::Refused(said(error));
        let wallet = Described::parse(&descriptor).map_err(refused)?;
        let psbt = spend::parse(&psbt_base64).map_err(refused)?;
        let shown =
            spend::as_shown(&wallet, &psbt, &unsigned_txid, &SCAN_STORE).map_err(refused)?;
        self.running
            .get()
            .ok_or_else(closed)?
            .sign_wallet(wallet, shown)
            .await
    }

    /// Ends the link and waits until it is down, also when a failure or another call is
    /// already ending it. A request in flight finishes first. It does nothing until `connect`
    /// has returned: cancel a `connect` that is still running instead.
    pub async fn disconnect(&self) -> Result<(), BleError> {
        match self.running.get() {
            Some(running) => running.disconnect().await,
            None => Ok(()),
        }
    }
}

impl WalletLink {
    /// Hands back the pairing credential `connecting` made, if any.
    async fn attach(
        &self,
        connecting: impl Future<Output = Result<(Running, Option<Vec<u8>>), BleError>>,
    ) -> Result<Option<Vec<u8>>, BleError> {
        if self.claimed.swap(true, Ordering::SeqCst) {
            return Err(BleError::Refused(
                "this WalletLink has already connected or tried to; make a new one".into(),
            ));
        }
        let (running, credential) = connecting.await?;
        // One caller got past `claimed`, so nothing else has set it.
        let _ = self.running.set(running);
        Ok(credential)
    }
}

impl Running {
    fn spawn(wallet: impl Wallet) -> Self {
        let (requests, inbox) = mpsc::unbounded_channel();
        let (link_dropped_sender, link_dropped) = oneshot::channel();
        let (task_ended, task_running) = mpsc::channel(1);
        tokio::spawn(async move {
            let _task_running = task_running;
            serve(wallet, inbox, link_dropped).await;
        });
        Self {
            requests,
            _link_dropped: link_dropped_sender,
            task_ended,
        }
    }

    async fn info(&self) -> Result<WalletInfo, BleError> {
        let (reply, answer) = oneshot::channel();
        self.requests
            .send(Request::Info(reply))
            .map_err(|_| closed())?;
        answer.await.map_err(|_| closed())?
    }

    async fn unlock(&self) -> Result<(), BleError> {
        let (reply, answer) = oneshot::channel();
        self.requests
            .send(Request::Unlock(reply))
            .map_err(|_| closed())?;
        answer.await.map_err(|_| closed())?
    }

    async fn account_xpub(&self, path: String) -> Result<HwAccountKey, BleError> {
        let (reply, answer) = oneshot::channel();
        self.requests
            .send(Request::Xpub { path, reply })
            .map_err(|_| closed())?;
        answer.await.map_err(|_| closed())?
    }

    async fn sign_psbt(
        &self,
        psbt_base64: String,
        signer_fingerprint: String,
    ) -> Result<String, BleError> {
        let (reply, answer) = oneshot::channel();
        self.requests
            .send(Request::SignPsbt {
                psbt_base64,
                signer_fingerprint,
                reply,
            })
            .map_err(|_| closed())?;
        answer.await.map_err(|_| closed())?
    }

    async fn sign_wallet(
        &self,
        wallet: Described,
        shown: SpendReview,
    ) -> Result<SpendReview, BleError> {
        let (reply, answer) = oneshot::channel();
        self.requests
            .send(Request::SignWallet {
                wallet: Box::new(wallet),
                shown,
                reply,
            })
            .map_err(|_| closed())?;
        answer.await.map_err(|_| closed())?
    }

    async fn disconnect(&self) -> Result<(), BleError> {
        let (reply, answer) = oneshot::channel();
        // A refused send means the task is already ending the link.
        let _ = self.requests.send(Request::Disconnect(reply));
        let result = answer.await.unwrap_or(Ok(()));
        self.task_ended.closed().await;
        result
    }
}

trait Wallet: Send + 'static {
    fn info(&mut self) -> impl Future<Output = Result<WalletInfo, BleError>> + Send;
    fn unlock(&mut self) -> impl Future<Output = Result<(), BleError>> + Send;
    fn xpub(&mut self, path: &str) -> impl Future<Output = Result<HwAccountKey, BleError>> + Send;
    fn sign_psbt(
        &mut self,
        psbt_base64: &str,
        signer_fingerprint: &str,
    ) -> impl Future<Output = Result<String, BleError>> + Send;
    fn disconnect(self) -> impl Future<Output = Result<(), BleError>> + Send;
}

async fn serve(
    wallet: impl Wallet,
    inbox: mpsc::UnboundedReceiver<Request>,
    link_dropped: oneshot::Receiver<()>,
) {
    let (wallet, close_reply) = answer_requests(wallet, inbox, link_dropped).await;
    let closed = wallet.disconnect().await;
    if let Some(reply) = close_reply {
        let _ = reply.send(closed);
    }
}

/// Drives one device call. Returns true when the link should disconnect.
///
/// A caller that already left does not put its request on the device.
async fn drive_call<T>(
    reply: oneshot::Sender<Result<T, BleError>>,
    link_dropped: &mut oneshot::Receiver<()>,
    call: impl Future<Output = Result<T, BleError>>,
) -> bool {
    if reply.is_closed() {
        return false;
    }
    let outcome = tokio::select! {
        outcome = call => outcome,
        _ = &mut *link_dropped => return true,
    };
    let lost = outcome
        .as_ref()
        .is_err_and(|error| !error.leaves_link_usable());
    let _ = reply.send(outcome);
    lost
}

/// Owns the inbox, so it is closed on return and queued requests fail before the disconnect starts.
async fn answer_requests<W: Wallet>(
    mut wallet: W,
    mut inbox: mpsc::UnboundedReceiver<Request>,
    mut link_dropped: oneshot::Receiver<()>,
) -> (W, Option<oneshot::Sender<Result<(), BleError>>>) {
    while let Some(request) = inbox.recv().await {
        match request {
            Request::Info(reply) => {
                if drive_call(reply, &mut link_dropped, wallet.info()).await {
                    break;
                }
            }
            Request::Unlock(reply) => {
                if drive_call(reply, &mut link_dropped, wallet.unlock()).await {
                    break;
                }
            }
            Request::Xpub { path, reply } => {
                if drive_call(reply, &mut link_dropped, wallet.xpub(&path)).await {
                    break;
                }
            }
            Request::SignPsbt {
                psbt_base64,
                signer_fingerprint,
                reply,
            } => {
                if drive_call(
                    reply,
                    &mut link_dropped,
                    wallet.sign_psbt(&psbt_base64, &signer_fingerprint),
                )
                .await
                {
                    break;
                }
            }
            Request::SignWallet {
                wallet: described,
                shown,
                reply,
            } => {
                if drive_call(
                    reply,
                    &mut link_dropped,
                    sign_wallet(&mut wallet, &described, shown),
                )
                .await
                {
                    break;
                }
            }
            Request::Disconnect(reply) => return (wallet, Some(reply)),
        }
    }
    (wallet, None)
}

/// Signs `shown`, a payment of `wallet` checked before it reached the device task, with the key of `wallet` that
/// `device` holds. `shown` comes back as it is when that key already signed, since a Jade answers a PSBT it signed
/// with no new signature. Else the vendor's own checks run, and the answer must be the same payment with that key's
/// signature on every input.
async fn sign_wallet(
    device: &mut impl Wallet,
    wallet: &Described,
    shown: SpendReview,
) -> Result<SpendReview, BleError> {
    let fingerprint = held_key(device, wallet).await?;
    if shown.signed.contains(&fingerprint) {
        return Ok(shown);
    }
    let signed = device.sign_psbt(&shown.psbt, &fingerprint).await?;
    let out_of_step = |why: String| BleError::Protocol(format!("the device's signed PSBT: {why}"));
    let after = spend::parse(&signed)
        .and_then(|psbt| spend::as_shown(wallet, &psbt, &shown.unsigned_txid, &SCAN_STORE))
        .map_err(|error| out_of_step(said(error)))?;
    if !after.signed.contains(&fingerprint) {
        return Err(out_of_step(format!(
            "key {fingerprint} has not signed every input"
        )));
    }
    Ok(after)
}

/// The master fingerprint of the key of `wallet` that `device` holds, once the device's account key at that key's
/// path is that key, else `WrongKey` before anything shows on the device. The parse leaves one key per fingerprint.
async fn held_key(device: &mut impl Wallet, wallet: &Described) -> Result<String, BleError> {
    let keys = wallet.keys();
    let first = device.xpub(&derivation_path_string(&keys[0].path)).await?;
    let Some(key) = keys
        .iter()
        .find(|key| key.fingerprint.to_string() == first.master_fingerprint)
    else {
        return Err(BleError::WrongKey(format!(
            "this device's master fingerprint {} is not one of this wallet's keys",
            first.master_fingerprint
        )));
    };
    let path = derivation_path_string(&key.path);
    let read = if key.path == keys[0].path {
        first
    } else {
        device.xpub(&path).await?
    };
    let held = Xpub::from_str(&read.xpub)
        .map_err(|error| BleError::Protocol(format!("the device's account key: {error}")))?;
    // These two decide every key derived below the account; the other xpub fields only say where it came from.
    if (held.public_key, held.chain_code) != (key.xpub.public_key, key.xpub.chain_code) {
        return Err(BleError::WrongKey(format!(
            "this device's key at {path} is not the wallet's key of master fingerprint {}",
            key.fingerprint
        )));
    }
    Ok(key.fingerprint.to_string())
}

